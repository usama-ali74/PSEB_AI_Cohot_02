"""## Exercise 1B (Stretch)

**1B.5** Write `is_balanced(s)` using a **stack** that returns True if brackets `()[]{}` are balanced.
"""

def is_balanced(s):
    stack = []
    pairs = {')': '(', ']': '[', '}': '{'}

    for char in s:
        if char in '([{':
            stack.append(char)
        elif char in ')]}':
            if not stack or stack.pop() != pairs[char]:
                return False

    return len(stack) == 0

assert is_balanced("([]{})")
assert is_balanced("print(len([1, 2]))")
assert not is_balanced("(]")
assert not is_balanced("((")
print("✅ 1B.5 passed")

"""---
# Lab 1C: Object-Oriented Programming

A **class** is a blueprint. An **object** (instance) is one thing built from it.
`self` is the specific object a method is working on.

## Demo: BankAccount
"""

class BankAccount:
    bank_name = "AI Bank"                 # class attribute (shared)

    def __init__(self, owner, balance=0):
        self.owner = owner                # instance attributes
        self._balance = balance           # _ means "internal, don't touch directly"

    @property
    def balance(self):
        return self._balance

    def deposit(self, amount):
        if amount <= 0:
            raise ValueError("Deposit must be positive")
        self._balance += amount

    def withdraw(self, amount):
        if amount > self._balance:
            raise ValueError("Insufficient funds")
        self._balance -= amount

    def __str__(self):
        return f"{self.owner}: Rs {self._balance:,}"

    def __repr__(self):
        return f"BankAccount(owner={self.owner!r}, balance={self._balance})"

acc = BankAccount("Sadia", 1000)
acc.deposit(500)
acc.withdraw(200)
print(acc)
print(repr(acc))
print(acc.balance, BankAccount.bank_name)

"""## Demo: inheritance and polymorphism"""

class SavingsAccount(BankAccount):
    def __init__(self, owner, balance=0, rate=0.05):
        super().__init__(owner, balance)
        self.rate = rate

    def add_interest(self):
        self.deposit(self._balance * self.rate)

    def __str__(self):                   # override
        return "[Savings] " + super().__str__()

s = SavingsAccount("Bilal", 10_000)
s.add_interest()
for account in [acc, s]:                # same method name, different behaviour
    print(account)
print(isinstance(s, BankAccount))

