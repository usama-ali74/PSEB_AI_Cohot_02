"""## Demo: exceptions

Read tracebacks **from the bottom up**: the last line tells you the error type and message.
"""

def safe_int(text):
    try:
        value = int(text)
    except ValueError:
        print(f"Could not convert {text!r}")
        return None
    else:
        print("converted fine")
        return value
    finally:
        print("finally always runs")

print(safe_int("42"))
