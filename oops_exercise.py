class Student:
  school_name = "ABC School"
  def __init__(self, name, roll_no, marks):
    self.name = name
    self.roll_no = roll_no
    self.marks = marks

  def add_marks(self, marks):
    self.marks += marks

  def deduct_marks(self, marks):
    self.marks -= marks

  def check_result(self, marks):
    if marks >= 50:
      return "Pass"
    else:
      return "Fail"

  def display_info(self):
    print(f"School Name: {self.school_name}")
    print(f"Name: {self.name}")
    print(f"Roll No: {self.roll_no}")
    print(f"Marks: {self.marks}")

std_sara = Student("Sara", 101, 20)
std_sara.add_marks(10)
std_ali = Student("Ali", 102, 85)
std_ali.deduct_marks(5)
std_ahmed = Student("Ahmad", 103, 60)
std_ahmed.display_info()
print(std_ahmed.check_result(std_ahmed.marks))
std_sara.display_info()
print(std_sara.check_result(std_sara.marks))
std_ali.display_info()
print(std_ali.check_result(std_ali.marks))

